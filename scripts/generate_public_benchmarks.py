"""Generate the public, fully synthetic benchmark fixtures.

The output is deterministic and contains no third-party subtitle text. Run:

    python scripts/generate_public_benchmarks.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "tests" / "data"

SEMANTIC_QUOTA = {
    "CAT_A": ("direction", 20),
    "CAT_B": ("negation", 16),
    "CAT_C": ("pronoun", 16),
    "CAT_D": ("conjunction", 16),
    "CAT_E": ("lexicon", 12),
}

SEMANTIC_LABELS = {
    "direction": "方向样本",
    "negation": "否定样本",
    "pronoun": "人称样本",
    "conjunction": "连接样本",
    "lexicon": "术语样本",
}


def write_semantic_benchmark() -> None:
    lines = [
        "# SYNTHETIC ASMR semantic contract benchmark (80 cue)",
        "# origin=synthetic; generated by scripts/generate_public_benchmarks.py",
        "#id\tcategory\tsource\tcontext_cues\texpected_pattern\tforbidden_pattern\treference_zh",
    ]
    for prefix, (category, count) in SEMANTIC_QUOTA.items():
        for index in range(1, count + 1):
            source = f"合成{category}サンプル{index}です"
            reference = f"{SEMANTIC_LABELS[category]}{index}"
            lines.append(
                "\t".join(
                    (
                        f"{prefix}_{index:03d}",
                        category,
                        source,
                        "NONE",
                        re.escape(reference),
                        "不应出现",
                        reference,
                    )
                )
            )
    (DATA_DIR / "golden_asmr_benchmark.tsv").write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def write_qc_benchmark() -> None:
    lines = [
        "# SYNTHETIC QC calibration set",
        "# origin=synthetic; generated by scripts/generate_public_benchmarks.py",
        "#case_id\tcue\tsource\ttranslation\texpected\tnote",
    ]
    for index in range(1, 46):
        lines.append(
            "\t".join(
                (
                    f"syn_kana_{index:03d}",
                    "1",
                    f"合成かな例{index}",
                    f"合成假名样本{index}だよ",
                    "kana",
                    "synthetic kana residue",
                )
            )
        )
    for index in range(1, 46):
        lines.append(
            "\t".join(
                (
                    f"syn_latin_{index:03d}",
                    "1",
                    f"合成拉丁例{index}",
                    f"合成拉丁样本{index} Track",
                    "latin",
                    "synthetic disallowed latin token",
                )
            )
        )
    for index in range(1, 31):
        lines.append(
            "\t".join(
                (
                    f"syn_clean_{index:03d}",
                    "1",
                    f"合成清浄例{index}",
                    f"合成洁净样本{index}",
                    "",
                    "synthetic negative",
                )
            )
        )
    (DATA_DIR / "qc_golden.tsv").write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    write_semantic_benchmark()
    write_qc_benchmark()
    print("generated tests/data/golden_asmr_benchmark.tsv")
    print("generated tests/data/qc_golden.tsv")


if __name__ == "__main__":
    main()
